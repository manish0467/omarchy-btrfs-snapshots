class CliTests(unittest.TestCase):
    def run_mock(self, name, *extra):
        return run_cli("--state-dir", tempfile.mkdtemp(), "--mock", name,
                       "--config", json.dumps({"staleDays": 7}), "check", *extra)

    def test_normal(self):
        doc = self.run_mock("normal")
        self.assertEqual(doc["state"], "ok")
        self.assertEqual(doc["counts"]["total"], 3)
        self.assertEqual(doc["counts"]["boot_entries"], 3)
        self.assertEqual(doc["tiers"]["limine"]["status"], "ok")
        self.assertEqual(doc["tiers"]["snapper_full"], "denied")
        self.assertLess(doc["newest"]["age_seconds"], 3 * 3600)
        self.assertEqual(doc["creation"]["command"], bs.CREATION_COMMAND)

    def test_many(self):
        doc = self.run_mock("many")
        self.assertEqual(doc["state"], "ok")
        self.assertEqual(doc["counts"]["total"], 5)
        joined = " ".join(doc["creation"]["retention_lines"])
        self.assertIn("at least 5 of 5", joined)
        self.assertIn("will likely remove the oldest", joined)

    def test_none(self):
        doc = self.run_mock("none")
        self.assertEqual(doc["state"], "stale")
        self.assertEqual(doc["counts"]["total"], 0)

    def test_no_snapper(self):
        doc = self.run_mock("no-snapper")
        self.assertEqual(doc["state"], "unavailable")
        kinds = [e["kind"] for e in doc["errors"]]
        self.assertIn("missing", kinds)

    def test_no_configs(self):
        doc = self.run_mock("no-configs")
        self.assertEqual(doc["state"], "unavailable")
        kinds = [e["kind"] for e in doc["errors"]]
        self.assertIn("no-configs", kinds)

    def test_denied(self):
        doc = self.run_mock("denied")
        self.assertEqual(doc["state"], "unavailable")
        self.assertEqual(doc["tiers"]["snapper_full"], "denied")
        self.assertEqual(doc["tiers"]["limine"]["status"], "missing")

    def test_lowdisk(self):
        doc = self.run_mock("lowdisk")
        self.assertEqual(doc["state"], "lowdisk")
        self.assertGreaterEqual(doc["fs"]["percent_used"], 90)

    def test_stale(self):
        doc = self.run_mock("stale")
        self.assertEqual(doc["state"], "stale")
        self.assertGreater(doc["newest"]["age_seconds"], 8 * 86400)

    def test_esp_full_warning_but_ok_state(self):
        doc = self.run_mock("esp-full")
        self.assertEqual(doc["state"], "ok")
        kinds = [w["kind"] for w in doc["warnings"]]
        self.assertIn("esp_full", kinds)
        self.assertEqual(doc["esp"]["limit_percent"], 85)

    def test_full_tier_b_merge(self):
        doc = self.run_mock("full")
        self.assertEqual(doc["state"], "ok")
        self.assertEqual(doc["counts"]["total"], 4)
        self.assertEqual(doc["counts"]["boot_entries"], 3)
        types = {s["number"]: s["type"] for s in doc["snapshots"]}
        self.assertEqual(types[46], "single")
        self.assertEqual(types[43], "single")
        boot = {s["number"]: s["boot_entry"] for s in doc["snapshots"]}
        self.assertEqual(boot, {46: True, 45: True, 44: True, 43: False})
        self.assertEqual(doc["snapshots"][0]["config"], "root")

    def test_show_config_column_only_multi_config(self):
        self.assertFalse(self.run_mock("normal")["show_config_column"])

    def test_state_file_written_and_privacy_safe(self):
        state_dir = tempfile.mkdtemp()
        run_cli("--state-dir", state_dir, "--mock", "normal", "check")
        files = list(Path(state_dir).rglob("*.json"))
        self.assertTrue(files, "state.json should exist")
        for path in files:
            text = path.read_text(encoding="utf-8")
            for forbidden in ("cmdline", "machine-id", "cryptdevice", "UUID"):
                self.assertNotIn(forbidden, text)

    def test_bad_args_exit_2(self):
        for argv in (["check", "--wat"], ["--config", "{bad", "check"],
                     ["--mock", "does-not-exist", "check"], ["bogus"],
                     ["check", "check"]):
            out = io.StringIO()
            with contextlib.redirect_stdout(out), \
                    contextlib.redirect_stderr(io.StringIO()):
                self.assertEqual(bs.main(argv), 2, argv)

    def test_busy_doc_when_locked(self):
        state_dir = Path(tempfile.mkdtemp())
        lock_path = state_dir / "lock"
        with open(lock_path, "w") as fh:
            import fcntl
            fcntl.flock(fh, fcntl.LOCK_EX)
            doc = run_cli("--state-dir", str(state_dir), "--mock", "normal", "check")
            self.assertTrue(doc["busy"])
            self.assertEqual(doc["state"], "unknown")


if __name__ == "__main__":
    unittest.main()
