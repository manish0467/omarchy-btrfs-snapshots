class LimineParsingTests(unittest.TestCase):
    def setUp(self):
        self.rows, self.status = bs.parse_limite_conf(FIXTURE_LIMINE)

    def test_status_ok(self):
        self.assertEqual(self.status, "ok")

    def test_extracts_numbers_and_dates(self):
        self.assertEqual([r["number"] for r in self.rows], [46, 45, 44, 43])
        self.assertEqual(self.rows[0]["date_raw"], "2026-11-10 20:15:04")
        self.assertIsNotNone(self.rows[0]["date_epoch"])

    def test_extracts_descriptions(self):
        self.assertEqual(self.rows[0]["description"], "1.2.3-1")
        self.assertEqual(self.rows[1]["description"], "1.2.3-1")
        # the "not-a-date" entry has no comment before its kernel entries
        self.assertIsNone(self.rows[3]["description"])

    def test_kernel_comments_do_not_become_descriptions(self):
        for row in self.rows:
            self.assertNotIn("Kernel version", row["description"] or "")

    def test_deduplicates_kernel_entries(self):
        self.assertEqual(len(self.rows), 4)  # 46 appears on two kernel lines

    def test_unparsable_date_kept_as_raw(self):
        self.assertEqual(self.rows[3]["date_raw"], "not-a-date")
        self.assertIsNone(self.rows[3]["date_epoch"])

    def test_privacy_no_cmdline_bytes_kept(self):
        blob = json.dumps(self.rows)
        for forbidden in ("cryptdevice", "machine-id=0000", "EFI/Linux",
                          "limine_history", "quiet", "splash", "rootflags"):
            self.assertNotIn(forbidden, blob)

    def test_empty_section(self):
        rows, status = bs.parse_limite_conf("x\n  //Snapshots\n  comment: 0 / 5 snapshots\n")
        self.assertEqual((rows, status), ([], "empty"))

    def test_header_count_not_a_description(self):
        rows, _ = bs.parse_limite_conf(
            "  //Snapshots\n  comment: 5 / 5 snapshots\n"
            "  ///2026-01-01 00:00:00\n  comment: real desc\n"
            "  ////k\n  cmdline: rootflags=subvol=/@/.snapshots/7/snapshot\n")
        self.assertEqual(rows[0]["description"], "real desc")

    def test_no_section(self):
        rows, status = bs.parse_limite_conf("nothing here\n")
        self.assertEqual((rows, status), ([], "no-section"))

    def test_entry_without_number_dropped(self):
        rows, _ = bs.parse_limite_conf(
            "  //Snapshots\n  ///2026-01-01 00:00:00\n  comment: ghost\n")
        self.assertEqual(rows, [])


class DateAndNumberTests(unittest.TestCase):
    def test_parse_date_epoch(self):
        expected = int(time.mktime((2026, 11, 10, 20, 15, 4, 0, 0, -1)))
        self.assertEqual(bs.parse_date_epoch("2026-11-10 20:15:04"), expected)

    def test_parse_date_epoch_invalid(self):
        for bad in (None, "", "not-a-date", "2026-13-99 99:99:99", "2026-11-10"):
            self.assertIsNone(bs.parse_date_epoch(bad))

    def test_parse_snapshot_number(self):
        self.assertEqual(bs.parse_snapshot_number(42), 42)
        self.assertEqual(bs.parse_snapshot_number("42"), 42)
        self.assertEqual(bs.parse_snapshot_number(" 43 "), 43)
        self.assertIsNone(bs.parse_snapshot_number(None))
        self.assertIsNone(bs.parse_snapshot_number("no digits"))
        self.assertIsNone(bs.parse_snapshot_number(True))

    def test_parse_config_values(self):
        values = bs.parse_config_values(
            '# comment\nSUBVOLUME="/"\nNUMBER_LIMIT="5"\n'
            "NUMBER_LIMIT=10-50\nTIMELINE_CREATE=no\n")
        self.assertEqual(values["NUMBER_LIMIT"], "10-50")
        self.assertEqual(values["SUBVOLUME"], "/")
        self.assertEqual(values["TIMELINE_CREATE"], "no")

    def test_parse_limit(self):
        self.assertEqual(bs.parse_limit("5"), 5)
        self.assertEqual(bs.parse_limit("10-50"), 50)  # upper bound = hard cap
        self.assertIsNone(bs.parse_limit(""))
        self.assertIsNone(bs.parse_limit("auto"))


class SnapperListTests(unittest.TestCase):
    """Realistic `snapper --jsonout -c root list` shape (strings for numbers,
    as snapper emits them). Not obtainable without privileges on stock
    installs, so this fixture mirrors the documented output format."""

    FIXTURE = {"configs": [{"config": "root", "snapshots": [
        {"number": "46", "type": "single", "pre-number": "",
         "date": "2026-11-10 20:15:04", "user": "root",
         "description": "1.2.3-1", "cleanup": "number", "userdata": {}},
        {"number": "45", "type": "pre", "pre-number": "",
         "date": "2026-11-09 09:30:00", "user": "root",
         "description": "before big change", "cleanup": "number"},
    ]}]}

    def test_finds_rows_anywhere_in_document(self):
        rows = bs.parse_snapper_list(self.FIXTURE)
        self.assertEqual([r["number"] for r in rows], [46, 45])
        self.assertEqual(rows[0]["type"], "single")
        self.assertEqual(rows[0]["cleanup"], "number")
        self.assertEqual(rows[1]["description"], "before big change")

    def test_empty_cleanup_becomes_none(self):
        data = {"configs": [{"snapshots": [{"number": "1", "description": "x",
                                            "cleanup": ""}]}]}
        rows = bs.parse_snapper_list(data)
        self.assertIsNone(rows[0]["cleanup"])

    def test_description_clipped(self):
        data = {"configs": [{"snapshots": [{"number": "1",
                                            "description": "a" * 400}]}]}
        rows = bs.parse_snapper_list(data)
        self.assertEqual(len(rows[0]["description"]), bs.MAX_DESC_LEN)

    def test_clip_untrusted_text(self):
        self.assertEqual(bs.clip("a\nb\rc  "), "a b c")
        self.assertIsNone(bs.clip(None))
        clipped = bs.clip("x" * 300)
        self.assertEqual(len(clipped), bs.MAX_DESC_LEN)
        self.assertTrue(clipped.endswith("…"))


class MergeTests(unittest.TestCase):
    def test_tier_b_wins_and_flags_boot_entries(self):
        tier_b = [snapshot_row(46, 2000, boot=None, source="snapper"),
                  snapshot_row(43, 1000, boot=None, source="snapper")]
        tier_a = [snapshot_row(46, 2000, boot=True, source="limine")]
        merged = bs.merge_snapshots([{"name": "root", "subvolume": "/"}],
                                    tier_b, tier_a)
        self.assertEqual([r["number"] for r in merged], [46, 43])
        self.assertTrue(merged[0]["boot_entry"])
        self.assertFalse(merged[1]["boot_entry"])

    def test_tier_a_single_config_attribution(self):
        tier_a = [snapshot_row(46, 2000, cfg=None)]
        merged = bs.merge_snapshots([{"name": "root", "subvolume": "/"}],
                                    [], tier_a)
        self.assertEqual(merged[0]["config"], "root")

    def test_tier_a_multi_config_not_attributed(self):
        tier_a = [snapshot_row(46, 2000, cfg=None)]
        merged = bs.merge_snapshots([{"name": "root"}, {"name": "home"}],
                                    [], tier_a)
        self.assertIsNone(merged[0]["config"])


class ClassifyTests(unittest.TestCase):
    def setUp(self):
        self.fs = {"percent_used": 50.0}
        self.th = {"stale_days": 7, "disk_warn_percent": 90, "esp_warn_percent": 85}

    def test_ok(self):
        snaps = [snapshot_row(46, NOW - 3600)]
        self.assertEqual(bs.classify([{"name": "root"}], snaps, self.fs, self.th,
                                     "ok", False, NOW), "ok")

    def test_no_configs_no_data_unavailable(self):
        self.assertEqual(bs.classify([], [], self.fs, self.th, "missing", False, NOW),
                         "unavailable")

    def test_configs_but_no_data_source_unavailable(self):
        # limine file missing AND tier B denied -> we simply cannot see
        self.assertEqual(bs.classify([{"name": "root"}], [], self.fs, self.th,
                                     "missing", False, NOW), "unavailable")

    def test_no_snapshots_with_working_source_is_stale(self):
        self.assertEqual(bs.classify([{"name": "root"}], [], self.fs, self.th,
                                     "empty", False, NOW), "stale")

    def test_stale(self):
        snaps = [snapshot_row(46, NOW - 8 * 86400)]
        self.assertEqual(bs.classify([{"name": "root"}], snaps, self.fs, self.th,
                                     "ok", False, NOW), "stale")

    def test_stale_disabled_at_zero(self):
        snaps = [snapshot_row(46, NOW - 40 * 86400)]
        th = dict(self.th, stale_days=0)
        self.assertEqual(bs.classify([{"name": "root"}], snaps, self.fs, th,
                                     "ok", False, NOW), "ok")

    def test_lowdisk_wins(self):
        snaps = [snapshot_row(46, NOW - 3600)]
        fs = {"percent_used": 93.0}
        self.assertEqual(bs.classify([{"name": "root"}], snaps, fs, self.th,
                                     "ok", False, NOW), "lowdisk")


class RetentionTests(unittest.TestCase):
    def test_under_limit(self):
        lines = bs.retention_lines(3, False, 5, 5, None)
        self.assertIn("under the limit", lines[0])
        self.assertNotIn("will likely remove", " ".join(lines))

    def test_at_limit_names_oldest(self):
        lines = bs.retention_lines(5, False, 5, 5, 42)
        self.assertIn("You have 5 of 5 snapshots.", lines[0])
        self.assertIn("will likely remove the oldest (#42)", lines[1])

    def test_tier_a_count_is_at_least(self):
        lines = bs.retention_lines(5, True, 5, 5, 42)
        self.assertIn("at least 5", lines[0])

    def test_count_unknown_limit_known(self):
        lines = bs.retention_lines(None, False, 5, None, None)
        self.assertIn("count unknown", lines[0])
        self.assertIn("limit is 5", lines[0])

    def test_both_unknown(self):
        lines = bs.retention_lines(None, False, None, None, None)
        self.assertIn("may remove older snapshots", lines[0])

    def test_important_snapshot_note(self):
        lines = bs.retention_lines(3, False, 5, 5, None)
        self.assertTrue(any("Important snapshots" in line for line in lines))


