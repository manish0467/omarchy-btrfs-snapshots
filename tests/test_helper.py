ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "helper"))
import btrfs_snapshots as bs  # noqa: E402

NOW = 1762800000  # fixed "now" for deterministic classification tests


def mock_ctx(name, **kwargs):
    return bs.Context(Path(tempfile.mkdtemp()), {}, name, False)


def run_cli(*argv):
    """Call main() like the shell does and return the parsed JSON document."""
    out = io.StringIO()
    with contextlib.redirect_stdout(out):
        code = bs.main(list(argv))
    assert code == 0, "helper exited %d: %s" % (code, out.getvalue())
    return json.loads(out.getvalue())


def snapshot_row(number, epoch, desc="desc", boot=True, cfg="root", **extra):
    row = {"config": cfg, "number": number, "date_raw": "", "date_epoch": epoch,
           "description": desc, "type": None, "cleanup": None, "user": None,
           "pre_number": None, "boot_entry": boot, "source": "test"}
    row.update(extra)
    return row


